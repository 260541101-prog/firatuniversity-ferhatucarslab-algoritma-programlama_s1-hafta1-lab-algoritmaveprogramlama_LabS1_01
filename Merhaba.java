public class IkiIslem {
    public static void main(String[] args) {
        int a = 17;
        int b = 5;
        System.out.println("Toplam: " + (a + b));
        System.out.println("Fark: " + (a - b));
        System.out.println("Carpim: " + (a * b));
        System.out.println("Bolum: " + (a / b));
        System.out.println("Kalan: " + (a % b));
    }
}
